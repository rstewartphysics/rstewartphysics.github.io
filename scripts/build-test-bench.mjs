// Writes assets/js/test-bench-engine.js: the test bench's solver, part models,
// faults and scenario boards (BENCH-PLAN §1, R10), so the bench pages load one file.
//
// Sources: tools/generators/test-bench/. A scenario's stripboard layout is
// taken from tools/build-guides/circuits.mjs when a build guide draws that board
// (one board, never a copy), or else from tools/generators/test-bench/boards/. The bundle needs
// assets/js/stripboard.js (window.SBD) loaded first.
//
// Before writing, the tests in tb-tests.js run on the bundle exactly as it will
// ship. A failing test stops the build.
//
//   npm run bench                  test, then write the bundle
//   npm run bench -- --check       test, and fail if the committed bundle is out of date (CI)
//   npm run bench -- --sets 5000   random part sets per board in the table test (default 1000; --check 300)
//   npm run bench -- --report f.md also write every reading's range to f.md

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";
import vm from "node:vm";
import * as circuits from "../tools/build-guides/circuits.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "tools/generators/test-bench");
const ENGINE = join(ROOT, "tools/generators/stripboard/engine/sbd-engine.js");
const OUT = join(ROOT, "assets/js/test-bench-engine.js");
const args = process.argv.slice(2);
const CHECK = args.includes("--check");
const arg = k => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : null; };
const SETS = +(arg("--sets") ?? (CHECK ? 300 : 1000));

/* Scenario id -> the circuit that holds its board: a build guide's, or a bench board's. */
const BOARDS = { "555-astable": circuits.astable };
for (const f of readdirSync(join(SRC, "boards")).filter(f => f.endsWith(".mjs")).sort()) {
  const { board } = await import(pathToFileURL(join(SRC, "boards", f)).href);
  BOARDS[board.id] = board;
}

/* The circuit diagram is the build guide's own (circuits.mjs), drawn with the
   site bundle's circuit kit. Test points are marked so the bench can light them,
   and their positions kept, with the chip's pin ends, for the leads' markers. */
const kit = vm.createContext({ console });
vm.runInContext(readFileSync(join(ROOT, "assets/js/stripboard.js"), "utf8"), kit, { filename: "stripboard.js" });
function diagramOf(c) {
  const at = {};
  const tp = (x, y, label) => {
    at[label] = [x, y];
    return `<g class="tb-dtp" data-tp="${label}"><circle class="sbd-tp" cx="${x}" cy="${y}" r="6"/>` +
      `<text class="sbd-tpl" x="${x}" y="${y - 10}" text-anchor="middle">${label}</text></g>`;
  };
  const d = c.circuit(kit.SBD.circuit, tp);
  const pins = {};
  for (const [k, v] of Object.entries(d.pins || {})) pins["IC1." + k] = [v[0], v[1]];
  return { w: d.w, h: d.h, svg: d.groups.join(""), at: Object.assign(pins, at) };
}

const layouts = {};
for (const [id, c] of Object.entries(BOARDS)) {
  const L = c.layouts.strip, ref = L.reference;
  layouts[id] = {
    layout: {
      board: L.board,
      cuts: ref.cuts.map(x => typeof x === "string" ? x : x[0]),
      placements: ref.placements.map(p => ({ id: p.id, footprint: p.footprint, at: p.at, rot: p.rot || 0 })),
      links: ref.links.map(l => ({ a: l.a, b: l.b, colour: l.colour })),
      testpoints: ref.testpoints.map(t => ({ id: t.id, at: t.at }))
    },
    question: { id: c.id, board: L.board, components: c.components, target: c.target, dontcare: c.dontcare || [] },
    diagram: diagramOf(c)
  };
}

const MODULES = ["tb-parts.js", "tb-solver.js", "tb-faults.js"];
const scenarios = readdirSync(join(SRC, "scenarios")).filter(f => f.endsWith(".js")).sort();
const body = [];
for (const n of MODULES) body.push(`/* ---- ${n} ---- */\n${readFileSync(join(SRC, n), "utf8").trimEnd()}\n`);
body.push(`/* ---- layouts (from tools/build-guides/circuits.mjs and boards/) ---- */\n` +
  `(function (root) { (root.TB = root.TB || {}).LAYOUTS = ${JSON.stringify(layouts)}; })(typeof globalThis !== "undefined" ? globalThis : this);\n`);
for (const n of scenarios) body.push(`/* ---- scenarios/${n} ---- */\n${readFileSync(join(SRC, "scenarios", n), "utf8").trimEnd()}\n`);

const file =
  "/* GENERATED by scripts/build-test-bench.mjs from tools/generators/test-bench/ — do not edit.\n" +
  "   window.TB: the test bench solver. TB.bench(scenarioId, { fault, seed }) -> a board with real\n" +
  "   part values: power(on), run(seconds), meter(setting, { red, black, socket }), read(),\n" +
  "   probe({ tip }), probeRead(), leds(). Needs assets/js/stripboard.js (window.SBD) first. */\n" +
  body.join("");

/* Test the bundle as it will ship. */
const ctx = vm.createContext({ console });
vm.runInContext(readFileSync(ENGINE, "utf8"), ctx, { filename: "sbd-engine.js" });
vm.runInContext(file, ctx, { filename: "test-bench-engine.js" });
vm.runInContext(readFileSync(join(SRC, "tb-tests.js"), "utf8"), ctx, { filename: "tb-tests.js" });
const t0 = Date.now();
const res = ctx.TB.runTests({ sets: SETS, log: s => console.log(s) });
const secs = ((Date.now() - t0) / 1000).toFixed(1);

const report = arg("--report");
if (report) {
  const lines = [];
  for (const [sid, cases] of Object.entries(res.ranges)) {
    lines.push(`# ${sid}: readings over ${SETS + 3} boards per case (corners lo, mid, hi + ${SETS} random)`, "");
    const keys = [...new Set(Object.values(cases).flatMap(c => Object.keys(c)))];
    lines.push(`| Case | ${keys.join(" | ")} |`, `|---|${keys.map(() => "---").join("|")}|`);
    for (const [c, ks] of Object.entries(cases)) lines.push(`| ${c} | ${keys.map(k => ctx.TB.showRange(ks[k])).join(" | ")} |`);
    lines.push("");
  }
  writeFileSync(report, lines.join("\n"));
  console.log(`bench: wrote ranges to ${report}`);
}

if (res.fail) {
  console.error(`bench: ${res.fail} test(s) failed, ${res.pass} passed (${secs} s):`);
  for (const f of res.failures) console.error("  ✗ " + f);
  process.exit(1);
}
console.log(`bench: ${res.pass} tests passed (${SETS} random part sets per board, ${secs} s).`);

if (CHECK) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== file) {
    console.error("bench: assets/js/test-bench-engine.js is out of date — run npm run bench.");
    process.exit(1);
  }
  console.log("bench: assets/js/test-bench-engine.js matches its sources.");
} else {
  writeFileSync(OUT, file);
  console.log(`bench: wrote assets/js/test-bench-engine.js (${file.length.toLocaleString()} bytes).`);
}
