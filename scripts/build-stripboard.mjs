// Writes assets/js/stripboard.js: the stripboard engine and renderer, so any page can draw a
// board without carrying the 10 000-line Planner.
//
// The engine is not written here. It is bundled into the four builder/planner pages, which are
// built from their own sources, so this script COPIES the modules out of those pages and refuses
// to write anything if the four copies disagree. One engine, never a fork.
//
//   npm run stripboard          write assets/js/stripboard.js
//   npm run stripboard -- --check   fail if the committed file is out of date (CI)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PAGES = [
  "classes/electronics/stripboard-planner.html",
  "classes/electronics/stripboard-builder.html",
  "classes/electronics/breadboard-planner.html",
  "classes/electronics/breadboard-builder.html",
];
const MODULES = ["sbd-engine.js", "sbd-render.js", "sbd-circuit.js"];
const OUT = join(ROOT, "assets/js/stripboard.js");

function modulesOf(page) {
  const html = readFileSync(join(ROOT, page), "utf8");
  const marks = [...html.matchAll(/^\/\* ---- (.+?) ---- \*\/$/gm)];
  const out = {};
  marks.forEach((m, i) => {
    const end = i + 1 < marks.length ? marks[i + 1].index : html.indexOf("</script>", m.index);
    out[m[1]] = html.slice(m.index, end);
  });
  for (const name of MODULES) {
    if (!out[name]) throw new Error(`${page}: no "${name}" module in its bundle`);
  }
  return MODULES.map((name) => out[name]).join("");
}

const copies = PAGES.map((p) => [p, modulesOf(p)]);
const [firstPage, body] = copies[0];
for (const [page, text] of copies.slice(1)) {
  if (text !== body) {
    console.error(`stripboard: ${page} carries a different engine from ${firstPage}.`);
    console.error("Rebuild the builder pages from one source before extracting.");
    process.exit(1);
  }
}

const file =
  "/* GENERATED by scripts/build-stripboard.mjs from the Stripboard Planner bundle — do not edit.\n" +
  "   window.SBD: the board engine (SBD.BOARDS, SBD.FOOTPRINTS, SBD.nets …), the renderer\n" +
  "   (SBD.render.renderBoard({ board, question: { components }, attempt: { placements, cuts,\n" +
  "   links } }) -> SVG string) and the circuit-diagram kit (SBD.circuit). */\n" +
  body;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== file) {
    console.error("stripboard: assets/js/stripboard.js is out of date — run `npm run stripboard`.");
    process.exit(1);
  }
  console.log("stripboard: assets/js/stripboard.js matches the Planner bundle.");
} else {
  writeFileSync(OUT, file);
  console.log(`stripboard: wrote assets/js/stripboard.js (${file.length.toLocaleString()} bytes).`);
}
