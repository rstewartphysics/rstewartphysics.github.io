// Writes assets/js/stripboard.js: the stripboard engine and renderer, so any page can draw a
// board without carrying the 10 000-line Planner.
//
// The engine is not written here. Its sources are tools/generators/stripboard/engine/, and
// tools/generators/stripboard/page/build.py writes this bundle when it builds the four
// builder/planner pages, which load it. This script builds the same bytes from the same
// sources, so CI can prove the committed copy is current. One engine, never a fork.
//
//   npm run stripboard              write assets/js/stripboard.js
//   npm run stripboard -- --check   fail if the committed file is out of date (CI)

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENGINE = join(ROOT, "tools/generators/stripboard/engine");
const MODULES = ["sbd-engine.js", "sbd-render.js", "sbd-circuit.js"];
const OUT = join(ROOT, "assets/js/stripboard.js");

// must match BUNDLE_HEAD in build.py, or --check fails after a page build
const file =
  "/* GENERATED by tools/generators/stripboard/page/build.py from tools/generators/stripboard/engine/ — do not edit.\n" +
  "   window.SBD: the board engine (SBD.BOARDS, SBD.FOOTPRINTS, SBD.nets …), the renderer\n" +
  "   (SBD.render.renderBoard({ board, question: { components }, attempt: { placements, cuts,\n" +
  "   links } }) -> SVG string) and the circuit-diagram kit (SBD.circuit). */\n" +
  MODULES.map((n) => `/* ---- ${n} ---- */\n${readFileSync(join(ENGINE, n), "utf8").trimEnd()}\n`).join("");

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== file) {
    console.error("stripboard: assets/js/stripboard.js is out of date — run tools/generators/stripboard/page/build.py.");
    process.exit(1);
  }
  console.log("stripboard: assets/js/stripboard.js matches the engine sources.");
} else {
  writeFileSync(OUT, file);
  console.log(`stripboard: wrote assets/js/stripboard.js (${file.length.toLocaleString()} bytes).`);
}
